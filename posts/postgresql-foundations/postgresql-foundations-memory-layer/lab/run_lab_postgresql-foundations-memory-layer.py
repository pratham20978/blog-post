# --------------------------------------------------------------------------- plumbing
def pg_ctl(*args):
    return subprocess.run([str(PGBIN / "pg_ctl"), "-D", str(PGDATA), *args],
                          check=True, capture_output=True, text=True)


def restart_server():
    """Stop and start the postmaster. Empties shared buffers; the kernel cache survives."""
    pg_ctl("-w", "stop")
    pg_ctl("-w", "-o", '-h ""', "-o", f"-k {SOCK}", "-l", str(PGDATA / "server.log"), "start")
    time.sleep(0.5)


def dsn(db=DB):
    return f"host={SOCK} user={USER} dbname={db}"


def psql(sql, db=DB, title=None, note=None, record=True):
    """Run SQL through psql and keep its text output, exactly as a reader would see it."""
    out = subprocess.run([str(PGBIN / "psql"), "-X", "-q", "-h", str(SOCK), "-U", USER, "-d", db,
                          "-v", "ON_ERROR_STOP=1"],
                         input=sql, capture_output=True, text=True)
    if out.returncode != 0:
        raise RuntimeError(f"psql failed:\n{sql}\n{out.stderr}")
    text = out.stdout.rstrip("\n")
    if record:
        md.append(f"### {title}\n" if title else "")
        if note:
            md.append(f"{note}\n")
        md.append("```sql\n" + sql.strip() + "\n```\n")
        md.append("```text\n" + text + "\n```\n")
    return text


def q(sql, db=DB):
    """Scalar / row fetch through psycopg for the JSON side."""
    with psycopg.connect(dsn(db), autocommit=True) as c:
        return c.execute(sql).fetchall()


def rel_path(rel):
    return PGDATA / q(f"select pg_relation_filepath('{rel}')")[0][0]


def fincore(path):
    """Resident kernel-cache pages of a file, via util-linux fincore."""
    out = subprocess.run(["fincore", "--bytes", "--noheadings", "--output", "RES,PAGES,SIZE", str(path)],
                         capture_output=True, text=True, check=True).stdout.split()
    res, size = int(out[0]), int(out[2])
    return {"resident_bytes": res, "resident_8k_pages": res // 8192, "size_bytes": size, "size_8k_pages": size // 8192}


def drop_from_kernel_cache(path):
    """posix_fadvise(DONTNEED) needs no privilege on a file we own. Flush first so the
    kernel has nothing dirty to keep."""
    fd = os.open(path, os.O_RDONLY)
    try:
        os.fsync(fd)
        os.posix_fadvise(fd, 0, 0, os.POSIX_FADV_DONTNEED)
    finally:
        os.close(fd)


def rss_kb(pid):
    for line in open(f"/proc/{pid}/status"):
        if line.startswith("VmRSS:"):
            return int(line.split()[1])
    return None


def section(title, blurb=None):
    md.append(f"\n## {title}\n")
    if blurb:
        md.append(blurb + "\n")


def num(explain_text, pattern):
    m = re.search(pattern, explain_text)
    return int(m.group(1)) if m else None


