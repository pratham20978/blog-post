"""Reproducible lab for "How PostgreSQL Uses Memory" (postgresql-foundations, part 1).

Every number quoted in blog.md that came from a running server came from this script.
It drives a stock PostgreSQL 16.2 (the `pgserver` wheel's bundled binaries) with the
default postgresql.conf, on a data directory that lives on a real disk (not tmpfs), and
writes two files next to itself:

    captures.md    the psql output of every step, verbatim, in run order
    captures.json  the numbers the figures are drawn from

Prerequisites (see README.md): PGBIN pointing at a 16.x bin directory whose
share/extension carries pg_buffercache, pg_prewarm, pg_walinspect and pageinspect
(all four are stock contrib modules), `fincore` from util-linux, and a data directory
on a non-tmpfs filesystem.

Run:  PGBIN=/path/to/bin PGDATA=/path/to/pgdata python3 run_lab.py
"""
